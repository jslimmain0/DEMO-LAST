test('공동 편집 mock: WebSocket 참여·편집 메시지가 같은 호스트의 다른 탭에 전달된다', async () => {
  const { createServer } = require('node:http')
  const { once } = require('node:events')
  const { WebSocket } = await import('ws')
  const { installMockPresence } = await import('../dev/mock-desktop.mjs')
  const server = createServer()
  installMockPresence({ httpServer: server }, { connected: true })
  server.listen(0, '127.0.0.1'); await once(server, 'listening')
  const url = `ws://127.0.0.1:${server.address().port}/ws/presence?flowId=test`
  const a = new WebSocket(url + '&name=A'); const b = new WebSocket(url + '&name=B')
  const messages = []
  b.on('message', data => messages.push(JSON.parse(String(data))))
  try {
    await Promise.all([once(a, 'open'), once(b, 'open')])
    const received = new Promise((resolve, reject) => { const timeout = setTimeout(() => reject(new Error('편집 메시지 미수신')), 2000); b.on('message', data => { const message = JSON.parse(String(data)); if (message.t === 'editing') { clearTimeout(timeout); resolve(message) } }) })
    a.send(JSON.stringify({ t: 'editing', nodeId: 'request' }))
    assert.equal((await received).nodeId, 'request')
    assert.ok(messages.some(m => m.t === 'hello'))
  } finally { a.terminate(); b.terminate(); await new Promise(resolve => server.close(resolve)) }
})

test('mock API는 잘못된 요청을 JSON 오류로 응답하고 일반 페이지는 통과시킨다', async () => {
  const { mockApiPlugin } = await import('../dev/mock-api.mjs')
  let middleware
  mockApiPlugin().configureServer({ middlewares: { use: fn => { middleware = fn } } })
  const request = async (url, body) => {
    const req = { url, method: 'POST', async *[Symbol.asyncIterator]() { yield Buffer.from(body) } }
    const res = { statusCode: 200, setHeader() {}, end(value) { this.body = JSON.parse(value) } }
    await middleware(req, res, () => { res.passed = true })
    return res
  }
  assert.equal((await request('/api/v1/flows', '{')).statusCode, 400)
  assert.equal((await request('/api/v1/flows', 'null')).statusCode, 400)
  assert.equal((await request('/api/v1/unknown', '{}')).statusCode, 501)
  assert.equal((await request('/mock/ws/public/payments', '{}')).statusCode, 404)
  assert.equal((await request('/relay/local/example/cb/wait', '{}')).statusCode, 404)
  assert.equal((await request('/flows', '')).passed, true)
})
