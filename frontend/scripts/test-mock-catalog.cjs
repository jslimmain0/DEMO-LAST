const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const ts = require('typescript')
const exported = {}
const source = fs.readFileSync(path.join(__dirname, '../src/lib/mockCatalog.ts'), 'utf8')
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: exported })
const input = { workspaces: [{ id: 'same', name: '공용', kind: 'PUBLIC' }], servers: [{ id: 'same-mock', workspaceId: 'same', slug: 'orders' }], ports: [{ mockId: 'same-mock', workspaceId: 'same', port: 18080 }], httpPort: 18080 }
const pc = exported.locatedFleet(input, 'local')
const server = exported.locatedFleet({ ...input, httpPort: 8080 }, 'server')
assert.notEqual(pc.servers[0].id, server.servers[0].id)
assert.equal(pc.workspaces[0].name, '내 PC')
assert.equal(input.servers[0].id, 'same-mock')
assert.equal(server.httpPort, 8080)
assert.equal(exported.mockLocation(pc.servers[0].id).origin, 'local')
assert.equal(exported.mockLocation(server.servers[0].workspaceId).id, 'same')
assert.throws(() => exported.mockLocation('same-mock'), /위치/)
console.log('PASS: local/server identical IDs have distinct UI identities, operations recover actual host/resource IDs without modifying responses')
