const original = JSON.stringify(spec)
const render = readOnly => TransportEditor({ spec, readOnly: !!readOnly, patch: patch => { spec = { ...spec, ...patch } } })
const control = label => walk(render(), node => node.props?.['aria-label'] === label)[0]
