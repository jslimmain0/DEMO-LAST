const assert = require('node:assert/strict')
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm'), ts = require('typescript')
function load(file, modules = {}) {
  const exported = {}
  vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(__dirname, '../src', file), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.ReactJSX } }).outputText, { exports: exported, TextEncoder, require: name => modules[name] ?? {} })
  return exported
}
const helpers = load('lib/protocolSpec.ts')
const jsx = (type, props) => typeof type === 'function' ? type(props) : { type, props }
const { TransportEditor } = load('components/ProtocolEditor.tsx', { 'react/jsx-runtime': { jsx, jsxs: jsx }, '../lib/protocolSpec': helpers, '../design/ui': { ui: {} } })
function walk(node, predicate, out = []) {
  if (Array.isArray(node)) node.forEach(child => walk(child, predicate, out))
  else if (node && typeof node === 'object') { if (predicate(node)) out.push(node); walk(node.props?.children, predicate, out) }
  return out
}
const text = node => Array.isArray(node) ? node.map(text).join('') : node && typeof node === 'object' ? text(node.props?.children) : typeof node === 'string' ? node : ''
const plain = value => JSON.parse(JSON.stringify(value))
